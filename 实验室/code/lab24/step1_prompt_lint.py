# 一个「提示词体检器」。真实工作中它可以是提交前的自检清单,
# 也可以做成 CI 里的一道闸——让提示词模板不靠记忆,而靠检查。

ELEMENTS = {
    "角色":   ["扮演", "作为一", "以……的身份"],
    "任务":   ["帮我", "请", "写一份", "总结", "改写", "生成", "分析"],
    "输出格式": ["格式", "JSON", "列表", "表格", "分三", "字数", "Markdown"],
    "示例":   ["例如", "示例", "举例", "比如", "像这样"],
    "约束":   ["不要", "必须", "只能", "不准", "避免", "至少", "不超过"],
}

PROMPTS = {
    "A 裸问": "帮我写个周报。",
    "B 加角色": "扮演一个做事细致的项目经理。帮我写一份本周工作周报。",
    "C 补格式和约束": "扮演一个做事细致的项目经理。帮我写一份本周工作周报。"
                     "用 Markdown 列表输出,分「本周完成」「下周计划」「风险」三块。"
                     "不要写空话,每条必须带具体数字。",
    "D 再加示例": "扮演一个做事细致的项目经理。帮我写一份本周工作周报。"
                  "用 Markdown 列表输出,分「本周完成」「下周计划」「风险」三块。"
                  "不要写空话,每条必须带具体数字。"
                  "例如:「完成登录接口联调,覆盖 12 个用例」。",
}

def lint(prompt):
    hit = {k: any(w in prompt for w in ws) for k, ws in ELEMENTS.items()}
    return hit, sum(hit.values())

print(f"{'提示词':<16}{'角色':>6}{'任务':>6}{'格式':>6}{'示例':>6}{'约束':>6}{'  得分':>8}")
for name, p in PROMPTS.items():
    hit, score = lint(p)
    row = "".join(f"{'✓' if hit[k] else '✗':>6}" for k in ELEMENTS)
    print(f"{name:<16}{row}{score:>6}/5")

print("\n同一件事,四版提示词的差距:")
print(f"   A 只有一句话:{len(PROMPTS['A 裸问']):>3} 字,只命中「任务」这一项")
print(f"   D 补全之后:  {len(PROMPTS['D 再加示例']):>3} 字,五项全中")
print(f"   D 的字数是 A 的 {len(PROMPTS['D 再加示例'])/len(PROMPTS['A 裸问']):.0f} 倍,但差距不在字数,在该给的信息给了没有。")

print("\n五个要素各自管什么:")
print("   角色    限定它从哪个角度说话(项目经理 / 法务 / 客服),直接影响用词和取舍")
print("   任务    说清要干什么 —— 这一项最容易自以为说了,其实没说")
print("   格式    让它输出能直接用的东西,而不是一段还得手工整理的话")
print("   示例    一个例子抵一段描述,尤其是「什么算好」这种说不清的标准")
print("   约束    划出边界:不要什么、必须什么 —— 这是最容易被忽略、也最省事的一项")

print("\n体检器的用法不是「必须五项全满」:")
print("   简单任务只给任务 + 格式就够;写示例反而啰嗦。")
print("   它的价值在于暴露「以为写了、其实没写」的项——")
print("   比如很多人以为说了格式,其实只说了「写得清楚点」。")
